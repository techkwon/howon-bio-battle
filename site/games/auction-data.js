/** 배수 → 전망 이름 (README 「크게 오름 · 그대로 · 걱정이 커짐」) */
export function trendOf(x) {
  if (x >= 2) return { label: '크게 오름', icon: '📈', cls: 'up2' };
  if (x > 1) return { label: '오름', icon: '↗️', cls: 'up' };
  if (x === 1) return { label: '그대로', icon: '➡️', cls: 'flat' };
  return { label: '걱정이 커짐', icon: '📉', cls: 'down' };
}

